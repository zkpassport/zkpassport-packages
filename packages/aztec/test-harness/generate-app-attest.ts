/**
 * Generates packages/aztec/noir/core/src/app_attest.nr from the `AppAttest` library of the L1
 * verifier's lib/Constants.sol, so the Aztec library checks face matches against the same app ids
 * and attestation root keys as L1. fixture-conformance.test.ts fails while the checked-in file is
 * stale.
 *
 * Run from the repo root: `bun packages/aztec/test-harness/generate-app-attest.ts`
 */
import { readFileSync, writeFileSync } from "fs"
import { fileURLToPath } from "url"

export const CONSTANTS_SOL = fileURLToPath(
  new URL("../../registry-contracts/src/lib/Constants.sol", import.meta.url),
)
export const APP_ATTEST_NR = fileURLToPath(
  new URL("../noir/core/src/app_attest.nr", import.meta.url),
)

export type SolidityConstant = { name: string; value: string; doc: string[] }

/**
 * A Solidity library's `bytes32 constant NAME = 0x...;` declarations, in source order, each with
 * the `//` comment lines directly above it. Throws on any other line in the library, so a
 * declaration in another form cannot be silently dropped.
 */
export function solidityBytes32Constants(source: string, library: string): SolidityConstant[] {
  const body = source.match(new RegExp(`library\\s+${library}\\s*\\{([^}]*)\\}`))?.[1]
  if (body === undefined) throw new Error(`no library ${library} in the Solidity source`)
  const constants: SolidityConstant[] = []
  let doc: string[] = []
  for (const raw of body.split("\n")) {
    const line = raw.trim()
    const comment = line.match(/^\/\/\s?(.*)$/)
    const constant = line.match(/^bytes32\s+constant\s+(\w+)\s*=\s*(0x[0-9a-fA-F]{64})\s*;$/)
    if (line === "") {
      doc = []
    } else if (comment) {
      doc.push(comment[1])
    } else if (constant) {
      constants.push({ name: constant[1], value: constant[2].toLowerCase(), doc })
      doc = []
    } else {
      throw new Error(`unrecognized line in library ${library}: ${line}`)
    }
  }
  return constants
}

/** app_attest.nr's contents for the given Constants.sol source, as `aztec-nargo fmt` leaves it. */
export function renderAppAttestNr(constantsSol: string): string {
  const constants = solidityBytes32Constants(constantsSol, "AppAttest")
  if (constants.length === 0) throw new Error("library AppAttest declares no constants")
  const header = [
    "//! GENERATED by packages/aztec/test-harness/generate-app-attest.ts from the `AppAttest` library",
    "//! of packages/registry-contracts/src/lib/Constants.sol. Do not edit: change Constants.sol and",
    "//! regenerate.",
    "//!",
    "//! The device attestation constants a face match proof is checked against: ZKPassport's app ids",
    "//! and the platforms' attestation root keys.",
  ].join("\n")
  const globals = constants.map(({ name, value, doc }) =>
    [...doc.map((line) => `/// ${line}`), `pub global ${name}: Field =`, `    ${value};`].join(
      "\n",
    ),
  )
  return [header, ...globals].join("\n\n") + "\n"
}

if (import.meta.main) {
  writeFileSync(APP_ATTEST_NR, renderAppAttestNr(readFileSync(CONSTANTS_SOL, "utf8")))
  console.log(`wrote ${APP_ATTEST_NR}`)
}
